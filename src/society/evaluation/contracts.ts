import type { Provenance, StrategyProfileSnapshot, StrategyProfileSnapshotId } from "../social/contracts";

export interface OpponentPoolEntry {
  entryId: string;
  strategyProfileSnapshotId: StrategyProfileSnapshotId;
  configurationHash: string;
  status: "baseline" | "candidate" | "frozen";
  supportedScenarioIds: string[];
  /**
   * Immutable, secret-free configuration captured from the source room. The
   * deployment registry still supplies the live provider endpoint and key
   * reference when this entry is executed.
   */
  strategyProfileSnapshot?: StrategyProfileSnapshot;
  modelFamilyLabel?: string;
  addedAt: string;
  provenance: Provenance;
  schemaVersion: number;
}

export interface CrossPlayBudget {
  maxRuns: number;
  maxConcurrentRooms: number;
  maxAgentActivations: number;
  maxTotalTokens: number;
  maxWallTimeMs: number;
}

export type CrossPlayPlanStatus =
  | "planned"
  | "running"
  | "completed"
  | "partial"
  | "failed"
  | "cancelled"
  | "interrupted";

export type CrossPlayRunSpecStatus =
  | "queued"
  | "running"
  | "completed"
  | "partial"
  | "failed"
  | "budget-exhausted"
  | "cancelled"
  | "interrupted";

export interface CrossPlayRunSpec {
  runSpecId: string;
  roomId: string;
  scenarioId: string;
  rounds: number;
  repetition: number;
  rotationIndex: number;
  /** Actor/seat id -> immutable source configuration. */
  seatBindings: Record<string, StrategyProfileSnapshotId>;
  /** Actor/seat id -> stable person. */
  characterBindings: Record<string, string>;
  /** Roles stay under scenario authority and are only observed after start. */
  roleAssignment: "scenario-runtime-observed";
  firstPlayerBalance: "seat-permutation";
  status: CrossPlayRunSpecStatus;
  agentActivations: number;
  totalTokens: number;
  reasoningDowngrades: number;
  providerFailures: number;
  observedRoleBindings?: Record<string, string>;
  archiveRef?: string;
  errorCode?: string;
  createdAt: string;
  startedAt?: string;
  finishedAt?: string;
  schemaVersion: number;
}

export interface CrossPlayPlan {
  planId: string;
  opponentPoolVersion: string;
  scenarioIds: string[];
  strategyProfileSnapshotIds: StrategyProfileSnapshotId[];
  status: CrossPlayPlanStatus;
  requestedReasoningEffort: "xhigh" | "high" | "provider-default";
  budget: CrossPlayBudget;
  runSpecs: CrossPlayRunSpec[];
  progress: {
    queuedRuns: number;
    runningRuns: number;
    finishedRuns: number;
    agentActivations: number;
    totalTokens: number;
    reasoningDowngrades: number;
    providerFailures: number;
  };
  evaluationId?: string;
  failureCode?: string;
  createdAt: string;
  startedAt?: string;
  finishedAt?: string;
  schemaVersion: number;
}

export interface FrozenOpponentPool {
  opponentPoolVersion: string;
  entries: OpponentPoolEntry[];
  configurationHash: string;
  createdAt: string;
  schemaVersion: number;
}

export interface CrossPlayRun {
  runId: string;
  planId?: string;
  runSpecId?: string;
  roomId: string;
  scenarioId: string;
  status: "completed" | "failed" | "partial";
  seatBindings: Record<string, StrategyProfileSnapshotId>;
  /** Actual snapshots generated by the new room, retained for drift audits. */
  executedSeatBindings?: Record<string, StrategyProfileSnapshotId>;
  roleBindings: Record<string, string>;
  worldSeed?: string;
  effectiveReasoningEffort: Record<string, "xhigh" | "high" | "provider-default">;
  downgradeEventIds: string[];
  payoff: Record<string, number>;
  archiveRef?: string;
  usage?: {
    agentActivations: number;
    totalTokens: number;
    wallTimeMs: number;
  };
  predictionCount: number;
  brierScore?: number;
  calibrationBins: Array<{ lower: number; upper: number; count: number; meanPrediction: number; empiricalRate: number }>;
  socialCausality: {
    decisionCount: number;
    decisionsWithObservation: number;
    decisionsWithEvidence: number;
    decisionsWithOutcome: number;
    influenceLinkedDecisions: number;
    commitmentCount: number;
    settledCommitmentCount: number;
    deceptionCount: number;
    detectedDeceptionCount: number;
    repairAttemptedDeceptionCount: number;
    repairedDeceptionCount: number;
    shadowSelectionCount: number;
    shadowAgreementCount: number;
  };
  failureCodes: string[];
  createdAt: string;
  schemaVersion: number;
}

export interface CrossPlayEvaluation {
  evaluationId: string;
  scenarioIds: string[];
  strategyProfileSnapshotIds: StrategyProfileSnapshotId[];
  opponentPoolVersion: string;
  runs: CrossPlayRun[];
  aggregate: {
    payoffMatrix: number[][];
    payoffSampleCounts: number[][];
    profileOrder: StrategyProfileSnapshotId[];
    seatAdjustedScores: Record<StrategyProfileSnapshotId, number>;
    meanBrierScore?: number;
    expectedCalibrationError?: number;
    predictionCount: number;
    socialCausalityCoverage: {
      observation: number;
      evidence: number;
      outcome: number;
      influence: number;
      commitmentSettlement: number;
      deceptionDetection: number | null;
      deceptionRepairAttempt: number | null;
      deceptionRepair: number | null;
      shadowAgreement: number | null;
    };
    reasoningDowngrades: number;
    providerFailures: number;
    completedRuns: number;
    partialRuns: number;
    failedRuns: number;
  };
  createdAt: string;
  schemaVersion: number;
}

export interface MetaStrategySelection {
  metaStrategyId: string;
  evaluationId: string;
  opponentPoolVersion: string;
  algorithm: "regret-matching";
  iterations: number;
  profileOrder: StrategyProfileSnapshotId[];
  distribution: Record<StrategyProfileSnapshotId, number>;
  expectedPayoff: number;
  bestResponseProfileSnapshotId?: StrategyProfileSnapshotId;
  bestResponsePayoff?: number;
  /** Diagnostic gap inside the frozen empirical matrix, not a Nash proof. */
  exploitabilityProxy?: number;
  createdAt: string;
  schemaVersion: number;
}

export interface EvaluationStoreState {
  schemaVersion: number;
  opponentPools: FrozenOpponentPool[];
  crossPlayPlans: CrossPlayPlan[];
  evaluations: CrossPlayEvaluation[];
  metaStrategies: MetaStrategySelection[];
}
