import puppeteer from "puppeteer-core";
import { strict as assert } from "node:assert";
import { mkdirSync } from "node:fs";
import { mindFixture } from "../tests/helpers/psychology-fixture.ts";
process.env.SOCIETY_DATABASE_FILE = ":memory:";
process.env.SOCIETY_MODEL_SETTINGS_FILE = "data/ui-models-test.json";
process.env.SOCIETY_CHARACTERS_FILE = "data/v4-ui/characters-test.json";
process.env.SOCIETY_OPERATOR_TOKEN = "ui-test-operator";
mkdirSync("data/v4-ui", { recursive: true });
const { context, createServerApp } = await import("../src/server/index.ts");
const { RunService } = await import("../src/runtime/run.ts");
const { runSpecSchema } = await import("../src/runtime/types.ts");
const { runtimeCharacter } = await import("../src/server/routes/runs.ts");
const characters = [context.characters.list().builtins[0], context.characters.list().builtins[3]].map(runtimeCharacter);
context.runs = new RunService(context.runs.store, character => ({ configuration: { kind: "scripted-ui-fixture" }, async turn(c) {
  const other = characters.find(p => p.id !== character.id);
  const source = c.recent.findLast(e => e.type === "action" || e.data.commitment) ?? c.recent.at(-1);
  const state = mindFixture(source.id, other.id);
  const repair = c.recent.findLast(e => e.data.action === "repair_transfer" && e.data.amount > 0);
  if (repair) { state.appraisal = "他确实拿出了自己的所得补偿。我愿意留一个机会，但这次要看行动。"; state.relationships[0].trust = -.2; state.strategy.kind = "probe"; }
  await c.call("update_mind", state);
  if (c.opportunity.actions.length) { for (const action of c.opportunity.actions) await c.call(action.name, { amount: action.name === "pledge_return" ? 50 : action.name === "invest" ? 6 : action.name === "repair_transfer" ? 5 : 0 }); return {}; }
  return { text: character.id === characters[0].id ? "话我听见了。你准备拿什么让我再信一次？" : "我先拿出五点补上，剩下的看下一轮。" };
} }));
const created = context.runs.create(runSpecSchema.parse({ scenario: "trust-game", trustProtocol: "pledge-repair", mode: "experiment", rounds: 2, roster: characters.map(c => ({ characterId: c.id })), budgets: { discussionTurns: 2 } }), characters);
await created.run.settled(); assert.equal(created.run.status, "completed");
const server = await new Promise(resolve => { const s = createServerApp().listen(0, "127.0.0.1", () => resolve(s)); });
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_BIN ?? "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
try {
  const page = await browser.newPage(); const errors = []; page.on("pageerror", e => errors.push(e.message));
  await page.setViewport({ width: 1512, height: 1000 }); await page.goto(base, { waitUntil: "networkidle2" });
  await page.screenshot({ path: "data/v4-ui/home-dark.png", fullPage: true });
  await page.evaluate(({ id, token }) => localStorage.setItem(`society:run:${id}:owner`, token), { id: created.run.id, token: created.ownerToken });
  await page.goto(`${base}/#/runs/${created.run.id}`, { waitUntil: "networkidle2" });
  await page.waitForSelector('.mind-panel [aria-label="主观信任"]');
  assert.equal(await page.$eval('[aria-label="主观信任"]', e => Number(e.getAttribute("aria-valuenow"))), 40);
  assert.equal(await page.$eval('.game-situation', e => e.textContent.includes('承诺未兑现')), true);
  await page.screenshot({ path: "data/v4-ui/arena-dark.png", fullPage: false });
  await page.locator('.mind-panel [role="tab"] ::-p-text(变化)').click();
  await page.waitForFunction(() => document.querySelector('.mind-panel').textContent.includes('随后实际发生'));
  await page.screenshot({ path: "data/v4-ui/mind-history.png", fullPage: false });
  await page.locator('button[aria-label="查看更新 1 的心理状态"]').click();
  await page.waitForFunction(() => document.querySelector('.mind-appraisal').textContent.includes('他当时如何理解'));
  assert.equal(await page.$eval('[aria-label="主观信任"]', e => Number(e.getAttribute("aria-valuenow"))), 17.5);
  assert.equal(await page.$eval('.mind-panel', e => e.scrollTop), 0);
  await page.locator('.mind-panel button ::-p-text(回到此刻)').click();
  await page.waitForFunction(() => document.querySelector('.mind-appraisal').textContent.includes('他如何理解此刻'));
  assert.equal(await page.$eval('[aria-label="主观信任"]', e => Number(e.getAttribute("aria-valuenow"))), 40);
  await page.locator('.mind-panel button ::-p-text(触发判断的经历)').click();
  await page.waitForSelector('.mind-evidence');
  const publicView = await (await fetch(`${base}/api/v2/runs/${created.run.id}`)).json();
  assert.equal(publicView.events.some(e => e.data.kind === "psychology"), false);
  await page.locator('[data-slot="sidebar-footer"] button[aria-label="切换外观"]').click();
  await page.locator('[role="menuitemradio"] ::-p-text(浅色)').click();
  await page.waitForFunction(() => !document.documentElement.classList.contains('dark'));
  await page.waitForSelector('[role="menu"]', { hidden: true });
  await page.screenshot({ path: "data/v4-ui/arena-light.png", fullPage: false });
  await page.setViewport({ width: 390, height: 844 });
  await page.locator('button[aria-label="查看人物"]').click();
  await page.waitForSelector('[data-slot="sheet-content"]');
  await page.locator('[data-slot="sheet-content"] .person-row').click();
  await page.waitForSelector('[data-slot="sheet-content"] .mind-panel');
  await page.screenshot({ path: "data/v4-ui/mind-mobile.png", fullPage: false });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.keyboard.press('Escape'); await page.goto(base, { waitUntil: "networkidle2" });
  await page.screenshot({ path: "data/v4-ui/home-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('Psychology UI passed: actual ledger, private state, historical state inspection and return to present, evidence, dark/light and mobile. Screenshots use a scripted fixture.');
} finally { await browser.close(); context.liveConnections.closeAll(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); context.runs.store.close(); }
